def rep(path, old, new, count=1):
    with open(ROOT + path, encoding='utf-8') as f:
        s = f.read()
    n = s.count(old)
    assert n == count, f'{path}: 期望 {count} 处，实际 {n} 处 —— old 片段前 60 字: {old[:60]!r}'
